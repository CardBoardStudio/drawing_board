const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {safeUrl, issueBody, issueLink, normalize} = require('../prototypes/galactic-reach/playtest-notes.js');
const context = {game: 'Galactic Reach', rules: '10.15', round: '3', phase: 'Buy', active: 'You', url: 'http://127.0.0.1:3110/?table=private&invite=secret#token'};
assert.equal(safeUrl(context.url), 'http://127.0.0.1:3110/');
assert.equal(safeUrl('javascript:alert(1)'), '');
assert.equal(safeUrl('https://person:password@example.com/game?session=secret'), 'https://example.com/game');
const notes = [{id: 'a', text: 'Expected the control to explain its price.\nSecond line.', target: {label: 'Add 5 storage', coord: '1,-2'}, context, createdAt: '2026-11-08T12:00:00Z', include: true}, {id: 'b', text: 'DO NOT INCLUDE', include: false}];
const body = issueBody(notes, context);
assert.match(body, /rules 10\.15 · round 3 · Buy/);
assert.match(body, /Map hex: 1,-2/);
assert.match(body, /Second line\./);
assert(!body.includes('DO NOT INCLUDE') && !body.includes('private') && !body.includes('secret'));
const link = issueLink('A title with & and #', body), parsed = new URL(link.url);
assert.equal(parsed.host, 'github.com');
assert.equal(parsed.pathname, '/CardBoardStudio/drawing_board/issues/new');
assert.equal(parsed.searchParams.get('body'), body);
assert.equal(parsed.searchParams.get('title'), 'A title with & and #');
assert.equal(link.needsCopy, false);
const long = issueLink('Long issue', 'x'.repeat(20000));
assert(long.needsCopy && !new URL(long.url).searchParams.has('body'), 'Long drafts use the visible copy-and-paste path without truncation');
const restored = normalize(JSON.parse(JSON.stringify({notes, draft: {text: 'unfinished', target: notes[0].target, context}, editing: null, title: 'Draft'})));
assert.equal(restored.notes[0].text, notes[0].text);
assert.equal(restored.draft.text, 'unfinished');
assert.equal(restored.draft.target.coord, '1,-2');
assert.deepEqual(normalize(null).notes, []);
assert.equal(normalize({notes: [null, {id: 'bad'}, ...notes]}).notes.length, 2);
console.log('Playtest notes: persistent draft format, selected notes, context and hex coordinates, private URL stripping, encoded GitHub composer, and long-issue fallback passed.');

const engine = fs.readFileSync(path.join(__dirname, '../prototypes/galactic-reach/app.js'), 'utf8');
const html = fs.readFileSync(path.join(__dirname, '../prototypes/galactic-reach/index.html'), 'utf8');
const expectedRules = engine.match(/const SAVE_FORMAT_VERSION = (\d+);/)[1] + '.' + engine.match(/const RULES_REVISION = (\d+);/)[1];
assert(html.includes('data-rules="' + expectedRules + '"'), 'Annotation context must report the actual rules version');
